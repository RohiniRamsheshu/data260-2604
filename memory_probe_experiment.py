import json
import time
import urllib.request
from pathlib import Path

import yaml


OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL = "qwen2.5:3b"


def load_probes():
    with open("memory_probes.yaml", "r", encoding="utf-8") as file:
        return yaml.safe_load(file)["probes"]


def call_ollama(prompt):
    payload = {
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
    }

    request = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    start = time.perf_counter()

    with urllib.request.urlopen(request, timeout=300) as response:
        data = json.loads(response.read().decode("utf-8"))

    latency_ms = (time.perf_counter() - start) * 1000
    return data.get("response", "").strip(), latency_ms


def build_conversation():
    return [
        "I am studying MongoDB memory systems.",
        "The application uses FastAPI as the web server.",
        "MongoDB stores messages persistently.",
        "Ollama is a local, stateless language model.",
        "We use the qwen2.5:3b model.",
        "Short-term memory contains recent messages.",
        "The memory sizes being compared are 4, 12, and 30 messages.",
        "Prompt tokens are text sent to the model.",
        "Response tokens are text generated by the model.",
        "Latency is the time required to receive a response.",
    ] + [
        f"Filler conversation message number {number}."
        for number in range(11, 31)
    ]


def build_prompt(conversation, memory_size, question):
    recent_messages = conversation[-memory_size:]

    context = "\n".join(
        f"Message: {message}"
        for message in recent_messages
    )

    return f"""
Answer the question using only the conversation context.

Conversation context:
{context}

Question:
{question}

Answer clearly and briefly.
"""


def main():
    probes = load_probes()
    conversation = build_conversation()
    results = []

    for memory_size in [4, 12, 30]:
        print(f"\nTesting memory size: {memory_size}")

        for probe in probes:
            prompt = build_prompt(
                conversation,
                memory_size,
                probe["question"],
            )

            answer, latency_ms = call_ollama(prompt)

            print(f"\nQuestion: {probe['question']}")
            print(f"Answer: {answer}")
            print(f"Latency: {latency_ms:.2f} ms")

            score = int(
                input("Enter quality score from 1 to 5: ")
            )

            results.append(
                {
                    "memory_size": memory_size,
                    "probe_id": probe["id"],
                    "question": probe["question"],
                    "answer": answer,
                    "score": score,
                    "latency_ms": round(latency_ms, 2),
                }
            )

    output_dir = Path("reports/hw06/raw")
    output_dir.mkdir(parents=True, exist_ok=True)

    output_path = output_dir / "memory-probe-results.json"

    output_path.write_text(
        json.dumps(results, indent=2),
        encoding="utf-8",
    )

    print(f"\nWrote {output_path}")


if __name__ == "__main__":
    main()